#!/usr/bin/env python3
"""Pre-submission checks for an agent-evaluation task.

    python3 tools/evalcheck.py [task-folder ...] [--json PATH] [--save] [--codes A10,E50]
    python3 tools/evalcheck.py --catalog          # the rule catalogue, as markdown

No arguments checks every tasks/NNN-* folder. Exit 1 on any ERROR.

ERROR is a defect in something we wrote (the rationale, the confidence note,
the ratings). NOTE is an observation about a harness output, which we cannot
edit: it is there to be cited in a rating, not fixed. REC never blocks.

Stdlib only, so it runs with the system python and needs no virtualenv.
"""
import argparse
import json
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from evalcheck import ERROR, NOTE, REC, TaskContext, catalog, find_tasks, run  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def print_catalog():
    print("# evalcheck rules\n")
    print("Generated by `python3 tools/evalcheck.py --catalog`. Do not edit by hand.\n")
    print("A-codes are prose checks; their patterns are in `tools/evalcheck/catalogs.py`")
    print("and their classes in [the prose references](prose/README.md). E-codes check the")
    print("evaluation itself and quote [the platform instructions](evaluation-instructions.md).\n")
    print("Scope `authored` is text we type into the platform, where a finding is an ERROR.")
    print("Scope `evidence` is a harness output, which we cannot edit, so a finding is a")
    print("NOTE to weigh under Format & Presentation. `both` runs over each at its own level.\n")
    print("| Code | Check | Scope | Rule | What it holds |")
    print("| --- | --- | --- | --- | --- |")
    for _family, _order, code, name, scope, rules, doc in catalog():
        print("| %s | `%s` | %s | %s | %s |" % (code, name, scope, rules or "-", doc))


def report_lines(ctx, report):
    out = ["%s: %d error(s), %d note(s), %d recommendation(s)"
           % (ctx.name, len(report.of(ERROR)), len(report.of(NOTE)), len(report.of(REC)))]
    for level in (ERROR, REC, NOTE):
        for f in report.of(level):
            out.append(f.line())
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("folders", nargs="*", help="task folders (default: every tasks/NNN-*)")
    ap.add_argument("--codes", help="only checks owning one of these codes, comma separated")
    ap.add_argument("--json", metavar="PATH", help="write the full report as JSON")
    ap.add_argument("--save", action="store_true",
                    help="write evaluation/checks/evalcheck-<date>.json in each task")
    ap.add_argument("--quiet", action="store_true", help="errors only")
    ap.add_argument("--catalog", action="store_true", help="print the rule catalogue and exit")
    args = ap.parse_args(argv)

    if args.catalog:
        print_catalog()
        return 0

    codes = [c.strip() for c in args.codes.split(",")] if args.codes else None
    folders = [Path(f) for f in args.folders] if args.folders else find_tasks(ROOT)
    if not folders:
        print("no task folders found under %s" % ROOT, file=sys.stderr)
        return 2

    failed, payloads = 0, []
    for folder in folders:
        ctx = TaskContext(folder)
        report = run(ctx, codes)
        failed += report.errors
        payload = report.as_dict(task=ctx.name, codes=codes)
        payload["generated"] = date.today().isoformat()
        payloads.append(payload)
        lines = report_lines(ctx, report)
        print(lines[0])
        if not args.quiet:
            for line in lines[1:]:
                print(line)
        elif report.errors:
            for f in report.of(ERROR):
                print(f.line())
        if args.save:
            d = Path(folder).resolve() / "evaluation" / "checks"
            d.mkdir(parents=True, exist_ok=True)
            p = d / ("evalcheck-%s.json" % payload["generated"])
            p.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n",
                         encoding="utf-8")
            try:
                shown = p.relative_to(ROOT)
            except ValueError:
                shown = p
            print("  saved %s" % shown)

    if args.json:
        Path(args.json).write_text(
            json.dumps(payloads if len(payloads) > 1 else payloads[0],
                       indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
